#!/usr/bin/env python3
"""Build src/climate-grid.js from the Köppen–Geiger 0.5° ASCII map (Kottek et al. 2006).

Source: http://koeppen-geiger.vu-wien.ac.at/data/Koeppen-Geiger-ASCII.zip (free to use with the citation below).
Usage: python3 scripts/climate/build-grid.py path/to/Koeppen-Geiger-ASCII.txt

The 720 × 360 grid (rows north to south from 89.75°, columns west to east from -179.75°) is run-length encoded:
each run is one class letter followed by its length in base 30 (omitted when 1), with ocean as class 0.
"""
import pathlib, sys

CLASSES = ['Ocean', 'Af', 'Am', 'As', 'Aw', 'BWh', 'BWk', 'BSh', 'BSk', 'Csa', 'Csb', 'Csc', 'Cwa', 'Cwb', 'Cwc', 'Cfa', 'Cfb', 'Cfc',
           'Dsa', 'Dsb', 'Dsc', 'Dsd', 'Dwa', 'Dwb', 'Dwc', 'Dwd', 'Dfa', 'Dfb', 'Dfc', 'Dfd', 'ET', 'EF']
SYMBOLS, DIGITS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdef', '0123456789ghijklmnopqrstuvwxyz'
W, H = 720, 360


def base30(n):
    s = ''
    while n:
        s, n = DIGITS[n % 30] + s, n // 30
    return s


def main(path):
    grid = [0] * (W * H)
    index = {c: i for i, c in enumerate(CLASSES)}
    for line in pathlib.Path(path).read_text().splitlines()[1:]:
        lat, lng, cls = line.split()
        row, col = round((89.75 - float(lat)) / .5), round((float(lng) + 179.75) / .5)
        grid[row * W + col] = index[cls]
    runs, i = [], 0
    while i < len(grid):
        j = i
        while j < len(grid) and grid[j] == grid[i]:
            j += 1
        runs.append(SYMBOLS[grid[i]] + (base30(j - i) if j - i > 1 else ''))
        i = j
    out = pathlib.Path(__file__).resolve().parents[2] / 'src' / 'climate-grid.js'
    out.write_text(
        '// Generated by scripts/climate/build-grid.py; do not edit. Köppen–Geiger climate classes on a 0.5° grid from\n'
        '// Kottek, M., J. Grieser, C. Beck, B. Rudolf and F. Rubel (2006): World Map of the Köppen–Geiger climate\n'
        '// classification updated. Meteorologische Zeitschrift 15, 259–263. Run-length encoded; see climate.js.\n'
        f'export const KOPPEN_CLASSES = {CLASSES!r};\n'.replace("'", '"') +
        f'export const KOPPEN_GRID = {{width: {W}, height: {H}, step: .5, symbols: "{SYMBOLS}", digits: "{DIGITS}", runs: "{"".join(runs)}"}};\n')
    print(f'{out}: {len(runs)} runs, {out.stat().st_size} bytes')


if __name__ == '__main__':
    main(sys.argv[1])
